create table if not exists public.outgoing_mail (
 id uuid primary key default gen_random_uuid(),
 record_number bigint generated by default as identity unique,
 sent_on date not null default current_date,
 recipient text not null,
 address text not null default '',
 subject text not null,
 reference text not null default '',
 method text not null default 'Pošta',
 tracking_number text not null default '',
 notes text not null default '',
 building_id uuid null,
 created_by uuid not null references auth.users(id),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create index if not exists outgoing_mail_sent_on_idx on public.outgoing_mail(sent_on desc);
create index if not exists outgoing_mail_created_by_idx on public.outgoing_mail(created_by);
alter table public.outgoing_mail enable row level security;
drop policy if exists "outgoing_mail_read_authenticated" on public.outgoing_mail;
create policy "outgoing_mail_read_authenticated" on public.outgoing_mail for select to authenticated using (true);
drop policy if exists "outgoing_mail_insert_own" on public.outgoing_mail;
create policy "outgoing_mail_insert_own" on public.outgoing_mail for insert to authenticated with check (created_by=auth.uid());
drop policy if exists "outgoing_mail_update_own" on public.outgoing_mail;
create policy "outgoing_mail_update_own" on public.outgoing_mail for update to authenticated using (created_by=auth.uid()) with check (created_by=auth.uid());
drop policy if exists "outgoing_mail_delete_own" on public.outgoing_mail;
create policy "outgoing_mail_delete_own" on public.outgoing_mail for delete to authenticated using (created_by=auth.uid());
drop policy if exists "outgoing_mail_admin_update" on public.outgoing_mail;
create policy "outgoing_mail_admin_update" on public.outgoing_mail for update to authenticated using (public.is_isys_admin()) with check (public.is_isys_admin());
drop policy if exists "outgoing_mail_admin_delete" on public.outgoing_mail;
create policy "outgoing_mail_admin_delete" on public.outgoing_mail for delete to authenticated using (public.is_isys_admin());
